/* ---------- Strapi ---------- */

async function strapi(pathname, init = {}) {
  // Long spawnSync OpenClaw calls block the event loop for minutes, which can
  // leave undici's pooled keep-alive socket dead — the next fetch then throws a
  // bare "fetch failed". Retry connection-level errors a few times (HTTP error
  // statuses are NOT retried — they surface immediately). Force Connection:
  // close so each request opens a fresh socket rather than reusing a stale one.
  let lastErr;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const res = await fetch(`${STRAPI_URL}${pathname}`, {
        ...init,
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${STRAPI_API_TOKEN}`,
          Connection: 'close',
          ...(init.headers || {}),
        },
      });
      if (!res.ok) {
        const body = await res.text().catch(() => '');
        throw new Error(`Strapi ${res.status} on ${pathname}: ${body.slice(0, 300)}`);
      }
      return res.json();
    } catch (e) {
      // Only retry genuine network failures ("fetch failed" / undici causes),
      // never a Strapi HTTP-status error (those messages start with "Strapi ").
      if (String(e.message).startsWith('Strapi ') || attempt === 4) throw e;
      lastErr = e;
      await sleep(1000 * attempt);
    }
  }
  throw lastErr;
}

async function fetchTargetAirlines() {
  const filters = [];
  if (argv.iata) filters.push(`filters[iataCode][$eqi]=${encodeURIComponent(argv.iata)}`);
  // If --overwrite, we take everything; otherwise only airlines with at least
  // one target field empty. Strapi $null filter with $or would be nicer but
  // its syntax varies across versions — easier to pull all and filter locally.
  const all = [];
  let page = 1;
  const pageSize = 100;
  while (true) {
    const q = [
      ...filters,
      `pagination[page]=${page}`,
      `pagination[pageSize]=${pageSize}`,
      'sort[0]=name:asc',
    ].join('&');
    const res = await strapi(`/api/airlines?${q}`);
    all.push(...res.data);
    if (res.data.length < pageSize) break;
    page++;
  }
  let skippedFullFaqs = 0;
  const eligible = all.filter((a) => {
    // --only-with-facts: skip airlines with no TravelPayouts route facts (their
    // FAQs can't be grounded in real route data anyway).
    if (argv['only-with-facts']) {
      const f = a.iataCode ? airlineFacts(a.iataCode) : null;
      if (!f || f.empty || f.destinationCount < 3) return false;
    }
    // Skip any airline whose FAQ section already shows the full 8 questions.
    if (!argv.overwrite && faqCount(a) >= MIN_FAQS) {
      skippedFullFaqs++;
      return false;
    }
    if (argv.overwrite) return true;
    const needsFactual = wantFields.some((f) => !a[f] || String(a[f]).trim() === '');
    // Fewer than 8 FAQs (or a thin About) → (re)generate the About + FAQ bundle.
    const needsAbout = wantAbout && (aboutNeedsWork(a.about) || faqCount(a) < MIN_FAQS);
    return needsFactual || needsAbout;
  });
  if (skippedFullFaqs > 0) {
    console.log(`Skipping ${skippedFullFaqs} airline(s) already showing 8 FAQs.`);
  }
  // Resume: skip checkpointed slugs — but NEVER skip an airline that still has
  // fewer than 8 FAQs. The FAQ count is the real "done" signal, so a page that
  // was checkpointed by an earlier run yet never got its FAQ set is retried
  // (this also makes the run self-healing: completed pages reach 8 FAQs and
  // drop out on their own, failed ones get another attempt).
  const toProcess = argv.resume
    ? eligible.filter((a) => faqCount(a) < MIN_FAQS || !checkpoint.processed.includes(a.slug))
    : eligible;
  return argv.limit > 0 ? toProcess.slice(0, argv.limit) : toProcess;
}

/* ---------- About generation (Claude prose + keyDestinations) ---------- */

// True when the about is empty or thinner than --min-paragraphs (and not
// protected by an existing substantial about, unless --overwrite).
function aboutNeedsWork(about) {
  const t = String(about || '').trim();
  if (!t) return true;
  return countParagraphs(t) < argv['min-paragraphs'];
}

// Count valid FAQ entries on a record. faqs is stored as JSON — an array of
// { q, a } objects (may arrive as a JSON string). Anything else → 0.
function faqCount(a) {
  let faqs = a && a.faqs;
  if (typeof faqs === 'string') {
    try { faqs = JSON.parse(faqs); } catch { return 0; }
  }
  if (!Array.isArray(faqs)) return 0;
  return faqs.filter((f) => f && f.q && f.a).length;
}

function countParagraphs(text) {
  const t = String(text).replace(/\r\n/g, '\n').trim();
  if (!t) return 0;
  const byBlank = t.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
  if (byBlank.length > 1) return byBlank.length;
  return t.split(/\n/).map((l) => l.trim()).filter(Boolean).length;
}

